"""Operating characteristics of the pre-registered confirmatory analyses on SIMULATED data (T2.10; revised
2026-09-26 after the preregistration review, review/prereg/response.md).

Runs vnsoc.analysis.confirmatory on data from simulate_study() under null and alternative scenarios, at the REGISTERED
bootstrap size (B = 10,000) and with the REGISTERED estimators, and writes every number to
prereg/analysis_plan/operating_characteristics.json (script output, never typed by hand); the table between the OC
markers in prereg/analysis_plan/README.md is regenerated from the same numbers.

Registered checks (rev-methods id 1, rev-editor id 2): in every null scenario the rejection rate of the registered
rule is at most 0.025 + 2 MCSE (MCSE = sqrt(0.025 * 0.975 / reps)) for H1, H4, the H3 least-favourable nulls and the
Holm family; H1 power at the protocol effect (30% vs 5%) is at least 0.95. The rules compared:
  H1  registered 'conservative' (BCa AND expanded BCa AND cluster jackknife-t AND wild cluster bootstrap-t),
      the protocol's textbook BCa alone, and the three-interval rule without the wild bootstrap;
  H4  registered (Mantel-Haenszel RR by model x language, value-stating answers, labels 3-5, guideline clusters,
      'conservative'), the same with BCa alone, and the pre-review estimator (crude pooled RR, loss W = labels 3-6).
Null scenarios keep abstentions concentrated in the disagreement group, model-specific disagreement shares and base
risks (Simpson confounding), k_i = 2 targets on 30% of conflict atoms and 5% decoy-less conflict atoms.

  cd "/d/phan chau trinh _ y khoa" && PYTHONUTF8=1 .venv/bin/python prereg/analysis_plan/simulate_operating_characteristics.py
  options: --workers N (default min(11, CPUs)), --n-boot B (default 10000 = registered), --quick (x0.1 replicates,
  no file writes), --render-only (re-render the README table and the registration summary from the JSON)
"""
